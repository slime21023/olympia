import type { SearchDocItem } from '../types.ts';
import { defineElement } from './define.ts';
import {
  docToResult,
  filterDocs,
  pagefindToResult,
  renderSearchResults,
  type PagefindResultData,
  type SearchResult,
} from './search-results.ts';

const PAGEFIND_PATH = '/pagefind/pagefind.js';
const MAX_FULLTEXT_RESULTS = 8;

interface PagefindModule {
  init(): Promise<void>;
  search(query: string): Promise<{ results: Array<{ data(): Promise<PagefindResultData> }> }>;
}

/** <o-search-modal data-docs="<json>">: Cmd/Ctrl+K command palette backed by Pagefind with a metadata fallback. */
class OlympiaSearchModal extends HTMLElement {
  private pagefind: PagefindModule | undefined;
  private pagefindRequested = false;
  private activeIndex = 0;

  private dialog!: HTMLDialogElement;
  private input!: HTMLInputElement;
  private resultsContainer!: HTMLElement;
  private engineStatus: HTMLElement | null = null;
  private docs: SearchDocItem[] = [];

  connectedCallback() {
    const dialog = this.querySelector<HTMLDialogElement>('dialog');
    const input = this.querySelector<HTMLInputElement>('#o-cmd-input');
    const resultsContainer = this.querySelector<HTMLElement>('#o-cmd-results');
    if (!dialog || !input || !resultsContainer) return;

    this.dialog = dialog;
    this.input = input;
    this.resultsContainer = resultsContainer;
    this.engineStatus = this.querySelector<HTMLElement>('#o-cmd-engine-status');
    this.docs = JSON.parse(this.getAttribute('data-docs') || '[]');

    // Fallback for browsers without <dialog closedby="any"> support per modern-web-guidance `light-dismiss-a-dialog`
    if (!('closedBy' in HTMLDialogElement.prototype)) {
      this.installLightDismissFallback();
    }

    for (const trigger of document.querySelectorAll('[data-search-open]')) {
      trigger.addEventListener('click', () => void this.open());
    }
    this.querySelector('[data-search-close]')?.addEventListener('click', () => dialog.close());

    document.addEventListener('keydown', (event) => {
      if (!(event.metaKey || event.ctrlKey) || event.key.toLowerCase() !== 'k') return;
      event.preventDefault();
      if (dialog.open) {
        dialog.close();
      } else {
        void this.open();
      }
    });

    input.addEventListener('input', () => void this.runSearch(input.value));
    input.addEventListener('keydown', (event) => this.handleInputKey(event));
  }

  private installLightDismissFallback() {
    this.dialog.addEventListener('click', (event) => {
      if (event.target !== this.dialog) return;
      const rect = this.dialog.getBoundingClientRect();
      const insideDialog =
        rect.top <= event.clientY &&
        event.clientY <= rect.top + rect.height &&
        rect.left <= event.clientX &&
        event.clientX <= rect.left + rect.width;
      if (!insideDialog) this.dialog.close();
    });
  }

  private async open() {
    if (!this.dialog.open) {
      this.dialog.showModal();
    }
    await this.loadPagefind();
    await this.runSearch(this.input.value);
    this.input.focus();
    this.input.select();
  }

  private async loadPagefind() {
    if (this.pagefindRequested) return;
    this.pagefindRequested = true;
    try {
      // Runtime-only: the Pagefind bundle is generated by the post-build indexing step, so it cannot be a static import.
      const pagefind: PagefindModule = await import(/* @vite-ignore */ PAGEFIND_PATH);
      await pagefind.init();
      this.pagefind = pagefind;
      if (this.engineStatus) this.engineStatus.textContent = 'Pagefind Full-Text Index';
    } catch {
      // Dev mode: no Pagefind index is built, so search falls back to the pre-indexed docs metadata.
    }
  }

  private async runSearch(query: string) {
    const trimmed = query.trim();
    if (trimmed && this.pagefind) {
      const fullText = await this.searchPagefind(this.pagefind, trimmed);
      if (fullText.length > 0) {
        this.render(fullText);
        return;
      }
    }
    this.render(trimmed ? filterDocs(this.docs, trimmed) : this.docs.map(docToResult));
  }

  private async searchPagefind(pagefind: PagefindModule, query: string): Promise<SearchResult[]> {
    try {
      const { results } = await pagefind.search(query);
      const top = await Promise.all(results.slice(0, MAX_FULLTEXT_RESULTS).map((result) => result.data()));
      return top.map(pagefindToResult);
    } catch {
      // Search failed: fall through to the metadata filter.
      return [];
    }
  }

  private render(results: SearchResult[]) {
    this.resultsContainer.innerHTML = renderSearchResults(results);
    this.activeIndex = 0;
  }

  private handleInputKey(event: KeyboardEvent) {
    const links = [...this.resultsContainer.querySelectorAll<HTMLAnchorElement>('.o-cmd-item')];
    if (links.length === 0) return;

    if (event.key === 'ArrowDown' || event.key === 'ArrowUp') {
      event.preventDefault();
      const delta = event.key === 'ArrowDown' ? 1 : -1;
      this.setSelected(links, (this.activeIndex + delta + links.length) % links.length);
    } else if (event.key === 'Enter') {
      event.preventDefault();
      this.dialog.close();
      window.location.href = links[this.activeIndex].href;
    }
  }

  private setSelected(links: HTMLAnchorElement[], index: number) {
    this.activeIndex = index;
    for (const [i, link] of links.entries()) {
      link.setAttribute('aria-selected', String(i === index));
    }
    links[index].scrollIntoView({ block: 'nearest' });
  }
}

defineElement('o-search-modal', OlympiaSearchModal);
